import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const schema=JSON.parse(await readFile(new URL('../schemas/benchmark.schema.json',import.meta.url)));
function type(s){
 if(s.$ref)return s.$ref.split('/').at(-1);
 if(s.enum)return s.enum.map(v=>JSON.stringify(v)).join(' | ');
 if(s.const!==undefined)return JSON.stringify(s.const);
 if(Array.isArray(s.type))return s.type.map(t=>type({...s,type:t})).join(' | ');
 if(s.type==='string')return 'string';if(s.type==='integer'||s.type==='number')return 'number';if(s.type==='boolean')return 'boolean';if(s.type==='null')return 'null';
 if(s.type==='array')return `Array<${type(s.items)}>`;
 if(s.type==='object')return `{ ${Object.entries(s.properties||{}).map(([k,v])=>`${JSON.stringify(k)}${s.required?.includes(k)?'':'?'}: ${type(v)}`).join('; ')} }`;
 throw Error('Unsupported benchmark schema type');
}
const text='// Generated by scripts/generate-benchmark-types.mjs from schemas/benchmark.schema.json.\n'+Object.entries(schema.$defs).map(([name,s])=>`export type ${name} = ${type(s)};`).join('\n')+'\n';
const path=new URL('../src/lib/api/benchmark-types.ts',import.meta.url);
if(process.argv.includes('--check'))assert.equal(await readFile(path,'utf8'),text,'Benchmark types are stale');else await writeFile(path,text);
