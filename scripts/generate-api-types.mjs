import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const schema=JSON.parse(await readFile(new URL('../schemas/site-v2.schema.json',import.meta.url)));
function type(s){
 if(s.$ref)return s.$ref.split('/').at(-1);
 if(s.enum)return s.enum.map(v=>JSON.stringify(v)).join(' | ');
 if(s.const!==undefined)return JSON.stringify(s.const);
 if(s.anyOf)return s.anyOf.map(type).join(' | ');
 if(Array.isArray(s.type))return s.type.map(t=>type({...s,type:t})).join(' | ');
 if(s.type==='string')return 'string';if(s.type==='integer'||s.type==='number')return 'number';if(s.type==='boolean')return 'boolean';if(s.type==='null')return 'null';
 if(s.type==='array')return `Array<${type(s.items)}>`;
 if(s.type==='object'){
  const props=Object.entries(s.properties||{}).map(([k,v])=>`${JSON.stringify(k)}${s.required?.includes(k)?'':'?'}: ${type(v)}`).join('; ');
  const additional=s.additionalProperties===false?'':`[key: string]: ${typeof s.additionalProperties==='object'?type(s.additionalProperties):'unknown'}`;
  return `{ ${props}${props&&additional?'; ':''}${additional} }`;
 };return 'unknown';
}
const source='// Generated by scripts/generate-api-types.mjs from schemas/site-v2.schema.json.\n'+Object.entries(schema.$defs).map(([name,def])=>`export type ${name} = ${type(def)};`).join('\n')+'\n';
const destination=new URL('../src/lib/api/types.ts',import.meta.url);
if(process.argv.includes('--check'))assert.equal(await readFile(destination,'utf8'),source,'API types are stale');else await writeFile(destination,source);
