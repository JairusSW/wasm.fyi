import {readFile,writeFile,mkdir,symlink,stat} from 'node:fs/promises';
import {join,resolve} from 'node:path';
const [rootArg,priorArg,planArg,siteArg,inputsArg]=process.argv.slice(2);
const root=resolve(rootArg),prior=resolve(priorArg),site=resolve(siteArg);
await mkdir(root,{recursive:true});
const plan=JSON.parse(await readFile(planArg));
await writeFile(join(root,'source-plan.json'),JSON.stringify(plan,null,2)+'\n');
const template=JSON.parse(await readFile(join(prior,'collection-template.json')));
template.anchor=plan.anchor;template.cutoff=plan.cutoff;template.captureDirectory=join(root,'captures');
template.harness=join(root,'frozen-harness');template.controller=join(root,'controller');
template.collection.runtimes=plan.pins.flatMap(p=>p.configurations);
template.collection.includeFeatures=false;template.collection.workers=1;
template.env.WASMFYI_HISTORY_FAST='1';
template.env.WASMFYI_GUEST_QUALIFY_CONFIGS=JSON.stringify(template.collection.runtimes);
template.env.WASMBENCH_TOOL_CACHE ||=template.toolRoot;
template.toolRoot ||=template.env.WASMBENCH_TOOL_CACHE;
for(const name of ['captures','failure-notes','builds','sdk-builds','engine-builds','repositories'])await mkdir(join(root,name),{recursive:true});
for(const name of ['frozen-harness','controller'])if(!await stat(join(root,name)).catch(()=>null))await symlink(join(prior,name),join(root,name));
await writeFile(join(root,'collection-template.json'),JSON.stringify(template,null,2)+'\n');
await writeFile(join(root,'runner-config.json'),JSON.stringify({site,node:process.execPath,inputs:resolve(inputsArg)},null,2)+'\n');
console.log(JSON.stringify({root,anchor:plan.anchor,engines:plan.pins.length,configurations:template.collection.runtimes.length,workloads:template.workloads.length,toolRoot:template.toolRoot}));
